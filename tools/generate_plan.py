#!/usr/bin/env python3
"""
Generates data/plan.json: a 70-week (16-month) couch-to-Ironman training plan.

Structure: six phases, each one calendar quarter (13 weeks) except the final
taper month (5 weeks), totalling 70 weeks / 16 months:

  A. Foundation        weeks  1-13  (months  1-3)
  B. Sprint Build       weeks 14-26  (months  4-6)  -> Sprint Triathlon
  C. Olympic Build      weeks 27-39  (months  7-9)  -> Olympic/Standard Triathlon
  D. Half-Iron Build    weeks 40-52  (months 10-12) -> Half-Iron (70.3)
  E. Ironman Build      weeks 53-65  (months 13-15) -> peak volume, no race
  F. Taper & Race       weeks 66-70  (month  16)    -> Full Ironman (140.6)

Within phases A-E, every 4th week (global week % 4 == 0) is a recovery
("cutback") week: run/bike/swim/brick volume is reduced ~25% so the body
absorbs the previous three weeks of build. Phase F is a hand-authored
monotonic taper, not generated by interpolation.

Weeks 1-21 (months 1-5) also layer in extra weekly runs, loosely mirroring a
novice marathon build-up that runs alongside the triathlon work: weeks 1-13
add a second run, and weeks 9-21 add a third. Instead of lerping each run
session independently, these weeks target an explicit total of weekly
running minutes (see MARATHON_RUN_RANGES, ramping 30-60 in month 1 up to
330-430 in month 5) and split that total across the week's run sessions by
fixed proportion, so the build reaches marathon-appropriate volume on
schedule. The weekly total still gets the same recovery-week cutback as
every other discipline. From week 22 on, run volume reverts to its
original, independently-lerped curves.

Run this script directly to (re)write ../data/plan.json.
"""
import json
import os

WEEKS_PER_PHASE = 13
TOTAL_WEEKS = 70


def round5(x):
    return int(round(x / 5.0) * 5)


def round50(x):
    return int(round(x / 50.0) * 50)


def lerp(start, end, i, n):
    """Linear interpolation for step i (0-indexed) of n total steps."""
    if n <= 1:
        return end
    return start + (end - start) * (i / (n - 1))


def is_recovery_week(global_week):
    return global_week % 4 == 0


def recovery_scale(global_week):
    return 0.75 if is_recovery_week(global_week) else 1.0


# Target total run-discipline minutes per week, by month, for the novice
# marathon build-up layered into weeks 1-21 (see module docstring).
MARATHON_RUN_RANGES = {
    1: (30, 60),
    2: (75, 130),    # +10% over original (70, 120)
    3: (150, 230),   # +15% over original (130, 200)
    4: (275, 360),   # +20% over original (230, 300)
    5: (410, 540),   # +25% over original (330, 430)
}

# Exact week range covered by each of those months (month 3 runs 5 weeks so
# every 13-week phase still splits 4/4/5, matching MONTH_WEEK_BOUNDARIES).
MARATHON_MONTH_WEEKS = {
    1: (1, 4),
    2: (5, 8),
    3: (9, 13),
    4: (14, 17),
    5: (18, 21),
}


def weekly_run_target(global_week):
    """Total run-discipline minutes targeted for this week, lerped across its
    month's range and recovery-scaled like every other discipline."""
    for month, (start, end) in MARATHON_MONTH_WEEKS.items():
        if start <= global_week <= end:
            low, high = MARATHON_RUN_RANGES[month]
            n = end - start + 1
            local_i = global_week - start
            return lerp(low, high, local_i, n) * recovery_scale(global_week)
    return None


def session(discipline, title, detail, duration_min=None, distance_m=None):
    s = {"discipline": discipline, "title": title, "detail": detail}
    if duration_min is not None:
        s["durationMin"] = duration_min
    if distance_m is not None:
        s["distanceM"] = distance_m
    return s


def rest_day():
    return []


REST_DETAIL = "Full rest day. Sleep, hydration, and easy stretching pay off here as much as any workout."


def run_detail(mins, tempo=False, hills=False):
    if hills:
        return f"{mins} min run with rolling hills or 4-6 short hill efforts — steady effort on the climbs, relaxed on the descents."
    if tempo:
        return f"{mins} min run — 10 min easy warm-up, then steady-hard tempo effort, 5 min easy cool-down."
    return f"{mins} min easy run — keep it conversational; consistent form matters more than pace."


def swim_detail(meters, phase):
    if phase == "A":
        return f"{meters}m total in the pool — mix of drills (catch-up, kick sets) and short easy swims with rest as needed. Technique over speed."
    if phase in ("B", "C"):
        return f"{meters}m — warm-up, then continuous-style swimming at a steady aerobic pace, short rest between sets as needed."
    return f"{meters}m long continuous swim — steady aerobic effort; if open water is available, practice sighting every 6-8 strokes."


def bike_detail(mins, tempo=False):
    if tempo:
        return f"{mins} min bike — warm up easy, then 3x8 min at a steady-hard effort with easy spinning recovery between, cool down easy."
    return f"{mins} min easy bike — flat-to-rolling terrain, conversational effort."


def brick_detail(bike_mins, run_mins):
    return (f"Bike {bike_mins} min steady, then Run {run_mins} min immediately off the bike. "
            "Practice the transition — the first few minutes of the run will feel heavy on tired legs; that's normal.")


def long_bike_detail(mins, brick_run_mins=None):
    base = f"{mins} min long ride — steady aerobic effort; practice race nutrition/hydration every 20-30 min."
    if brick_run_mins:
        base += f" Finish with a {brick_run_mins} min easy run straight off the bike."
    return base


def long_run_detail(mins):
    return f"{mins} min long run — steady aerobic pace; practice the nutrition/hydration you'd use on race day."


def strength_detail(mins):
    return f"{mins} min strength & mobility — core, glutes, hips, plus 5-10 min stretching or foam rolling."


