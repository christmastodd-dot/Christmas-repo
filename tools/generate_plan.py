    {
        "week": 26,
        "label": "Sprint Triathlon",
        "emoji": "\U0001F3C1",
        "distances": "750m swim / 20km bike / 5km run",
        "note": "Your first triathlon finish line! Race at an easy-hard effort and enjoy it — everything since week 1 has led here.",
    },
